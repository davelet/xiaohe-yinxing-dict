use super::super::*;

pub(crate) fn render_wt(ui: &mut Ui, nav: &mut HelpNav) {
    h2(ui, "4 常见问题解答");

    h4(ui, "一、只有一个候选字词？");
    bul(
        ui,
        "刚接触小鹤音形会发现怎么只有一个候选？这不正是你们找到小鹤的原因吗，无重码或低重码。",
    );
    bul(
        ui,
        "小鹤音形是四码定长方案，这不同于双拼或双拼+辅助码的智能输入方式，四码方案字词编码最长四码（称全码），可使用一二三简或全码的方式来输入，通常单字输入有简打简，四码全码且为首选时可连续输入，无需空格。小鹤音形的码表是按准无重码来设计的，基本都是首选上屏，少量次选上屏。空格为首选上屏键，分号为次选上屏键。",
    );
    sp(ui);

    h4(ui, "二、打全码出另一个字词？");
    p(
        ui,
        "比如想打“欢”字，结果hryr出的是“还原”，请看下面全码字部分的说明。",
    );
    sp(ui);

    h4(ui, "三、码表分类：全码字、词 二简次选 随心");
    bul(ui, "这四个码表分类有点特别，所以单独讲讲");
    num(
        ui,
        "1",
        "全码字：部分已出简码的字的全码，用于学习全码拆分，实际打字不需要",
    );
    p(
        ui,
        "有的字因为已经有简码而其四码全码和别的字词全码重码，这时则让出全码首选位置，称为“出简让全”。",
    );
    num(
        ui,
        "2",
        "全码词：部分已出简码的词的全码，如熟悉简码词，可清空此分类",
    );
    num(ui, "3", "二简次选：二简次选字，默认关闭，oej启用");
    num(ui, "4", "随心：这是一个自定规则的码表分类");
    sp(ui);

    h4(ui, "四、单字四码比双拼用键多？");
    bul(
        ui,
        "双拼的话每个字打两下就行了，如果再加上形的话岂不是要多击键了吗？这也是想当然的看法，其实并不是，原因如下：",
    );
    num(
        ui,
        "1",
        "双拼双形是指的单字全码的编码方式，并不是每个字都要打全码，主打的是一二三简码字",
    );
    num(
        ui,
        "2",
        "二字及二字以上词四键上屏，双拼用要五键七键九键（分别指二三四字词）",
    );
    bul(ui, "综合一下，双拼双形用键比双拼更少。");
    sp(ui);

    h4(ui, "五、四码上屏，总多打空格");
    p(
        ui,
        "有人刚开始用可能不习惯四码的自动上屏或后续码顶上屏，你只要记住四码词条是不需要空格来上屏的，只要是四码你就连着打。",
    );
    p(ui, "就首选字词来说，简码空格、全码连（全码即四码）。");
    sp(ui);

    h4(ui, "六、不会读的字怎么办？");
    p(
        ui,
        "可以键入查询字符（1左侧）替代双拼键位再加双形编码，候选字中可查看其双拼编码。",
    );
    sp(ui);

    h4(ui, "七、简码记忆");
    p(
        ui,
        "先说说小鹤码表的设计思想，单字理想的状态是通过一码到四码各安排一个字达到无重码状态。",
    );
    bul(
        ui,
        "记忆简码，一般在使用中手指就逐渐记忆了，不需要去背。也可以通过练习缩短掌握的时间，练习常用500字是个入门捷径。",
    );
    sp(ui);

    h4(ui, "八、词太少？主打字还是词？");
    p(ui, "嫌词少，这是新手较容易出现的问题。");
    p(ui, "要 学会 断 字 断 词，输入 的 灵活 也 从 这里 体现。");
    p(
        ui,
        "四码方案因为单字能力强，对词的依赖少，通常设计为小词库码表，单字是提速的基础。",
    );
    sp(ui);

    h4(ui, "九、小鹤字词库有多大？");
    p(
        ui,
        "小鹤音形5.0版开始采用《通用规范汉字表》国发〔2013〕23号文规定字表8105字。",
    );
    p(
        ui,
        "截至小鹤音形10.26.3版，单字编码1.38万（含简码、多音字、容错码），单字全码8726（含多音字、容错码），词编码5.75万，去重后词共计5.66万，其中二字词3.46万，三字词0.52万，四字词1.50万，四字以上词0.18万。",
    );
    p(ui, "另补充表外300余字，多为粤语用字及生活中可能用到的字。");
    qt(ui, "几个名词定义");
    qt(ui, "- 表外字+：《通用规范汉字表》未收录的字");
    qt(
        ui,
        "- 生僻字*：字频5500后的字，常规模式需用单引号引导（400余字）",
    );
    qt(ui, "- 出简让全-：字已有简码，全码让出首选位");

    hr(ui);
    navrow(ui, nav, Some(("3 文章", "wv")), Some(("5 指引", "vy")));
}
