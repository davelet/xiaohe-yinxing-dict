    bul(ui, "搜狗输入法");
    p(ui, "  搜狗五笔的win版、安卓版、iOS版均支持：自定义方案");
    bul(ui, "百度输入法");
    p(ui, "  安卓版、iOS版均支持：自定义方案");
    bul(ui, "rime");
